"""
Step 2: Custom PyTorch datasets, dynamic augmentation pipelines, and data loaders.

Reads splits.csv and oversampling_plan.json (generated by step1_split_data.py) to construct
the training, validation, and test DataLoader pipelines.

Key Design Elements:
    1. Training Pipeline:
       - Online dynamic oversampling: Each epoch draws every training sample once, plus
         a fresh random set of minority class instances up to that class's target count.
       - Stochastic augmentations: Flips, random resized crops, mild Gaussian blur,
         color jitter, and rotations padded with ImageNet mean color (124, 116, 104) so
         empty boundary corners normalize precisely to zero.
       - In-memory execution: No repeated images are ever written to disk.
    2. Validation & Test Pipelines:
       - Pure deterministic evaluation transforms (resize + ImageNet normalization).
       - Zero oversampling, zero data leakage, and natural class distributions.

Usage (standalone self-test):
    python src/step2_dataset.py
    python src/step2_dataset.py --batch-size 16 --num-workers 4
"""
import argparse
import csv
import json
import random
import time
from collections import Counter, defaultdict
from pathlib import Path

import torch
from PIL import Image
from torch.utils.data import DataLoader, Dataset, Sampler
from torchvision import transforms

ROOT = Path(__file__).resolve().parent.parent

# Standard ImageNet normalization parameters matching EfficientNet-B4 pretraining
IMAGENET_MEAN = (0.485, 0.456, 0.406)
IMAGENET_STD = (0.229, 0.224, 0.225)


def train_transform(size):
    """
    Constructs the stochastic data augmentation pipeline for training.
    
    Augmentations:
        - RandomResizedCrop: Scale (0.6 - 1.0) and aspect ratio (0.85 - 1.15) simulate varying camera distances.
        - RandomHorizontalFlip & RandomVerticalFlip: Rotational invariance for discarded waste items.
        - RandomRotation: Up to +/- 25 deg. Padding uses uint8 ImageNet mean (124, 116, 104) so that
          tensor normalization maps border padding directly to 0.0 (neutral input).
        - ColorJitter & GaussianBlur: Robustness against lighting variations and sensor noise.
    """
    return transforms.Compose([
        transforms.RandomResizedCrop(size, scale=(0.6, 1.0), ratio=(0.85, 1.15)),
        transforms.RandomHorizontalFlip(),
        transforms.RandomVerticalFlip(p=0.5),
        transforms.RandomRotation(25, fill=(124, 116, 104)),
        transforms.ColorJitter(brightness=0.3, contrast=0.3,
                               saturation=0.25, hue=0.03),
        transforms.RandomApply(
            [transforms.GaussianBlur(5, sigma=(0.1, 1.5))], p=0.15),
        transforms.ToTensor(),
        transforms.Normalize(IMAGENET_MEAN, IMAGENET_STD),
    ])


def eval_transform(size):
    """
    Constructs deterministic preprocessing for validation and test splits.
    Resizes images to target resolution and standardizes using ImageNet mean/std.
    """
    return transforms.Compose([
        transforms.Resize((size, size)),
        transforms.ToTensor(),
        transforms.Normalize(IMAGENET_MEAN, IMAGENET_STD),
    ])


def load_records(data_dir, splits_csv, class_to_idx):
    """
    Parses splits.csv into memory and builds file path mappings per split.
    Enforces strict assertion checks to guarantee zero data leakage between splits.
    """
    records = {"train": [], "val": [], "test": []}
    missing = []
    with open(splits_csv, newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            path = data_dir / row["path"]
            if not path.is_file():
                missing.append(str(path))
                continue
            records[row["split"]].append((str(path), class_to_idx[row["label"]]))
    if missing:
        raise FileNotFoundError(
            f"{len(missing)} images listed in {splits_csv} were not found, "
            f"e.g. {missing[:3]}. Re-run step1_split_data.py with --force if "
            "the dataset changed."
        )

    # Fail loudly if any sample overlaps across partitions
    seen = {s: {p for p, _ in records[s]} for s in records}
    assert not (seen["train"] & seen["val"]), "train/val overlap"
    assert not (seen["train"] & seen["test"]), "train/test overlap"
    assert not (seen["val"] & seen["test"]), "val/test overlap"
    return records


class WasteDataset(Dataset):
    """PyTorch Dataset loading RGB waste images and mapping category labels."""

    def __init__(self, records, transform):
        self.records = records
        self.transform = transform

    def __len__(self):
        return len(self.records)

    def __getitem__(self, index):
        path, label = self.records[index]
        with Image.open(path) as img:
            image = img.convert("RGB")
        return self.transform(image), label


class EpochOversampler(Sampler):
    """
    Custom Sampler yielding balanced index streams per training epoch.

    Mechanics:
        1. Base Coverage: Includes every original training sample exactly once per epoch.
        2. Dynamic Sampling: For under-represented classes, draws random extra samples
           without replacement up to the class's epoch_target.
        3. Fresh Variations: Re-samples minority extras each epoch. Combined with online
           data augmentations, every repeated draw presents unique pixel variations.
        4. Seed Synchronization: Training loops call set_epoch(epoch) so sampling sequences
           remain strictly reproducible across experimental runs.
    """

    def __init__(self, labels, targets, seed=42):
        self.seed = seed
        self.epoch = 0
        self.targets = targets
        self.by_class = defaultdict(list)
        for index, label in enumerate(labels):
            self.by_class[label].append(index)

    def set_epoch(self, epoch):
        """Sets the current epoch counter to advance the seeded RNG state deterministically."""
        self.epoch = epoch

    def epoch_indices(self, epoch):
        """Generates shuffled list of sample indices for the specified epoch."""
        rng = random.Random(self.seed + epoch)
        indices = []
        for label, members in self.by_class.items():
            indices.extend(members)
            extra = self.targets[label] - len(members)
            while extra > 0:
                take = min(extra, len(members))
                indices.extend(rng.sample(members, take))
                extra -= take
        rng.shuffle(indices)
        return indices

    def __iter__(self):
        indices = self.epoch_indices(self.epoch)
        self.epoch += 1
        return iter(indices)

    def __len__(self):
        return sum(max(self.targets[c], len(m)) for c, m in self.by_class.items())


def build_dataloaders(batch_size=16, num_workers=4, size=384,
                      data_dir=None, out_dir=None, seed=42):
    """
    Builds optimized PyTorch DataLoaders for train, val, and test partitions.
    
    Configures pinned memory for asynchronous GPU transfers and persistent workers
    to eliminate multi-processing initialization latency between epochs.
    """
    data_dir = Path(data_dir) if data_dir else ROOT / "data"
    out_dir = Path(out_dir) if out_dir else ROOT / "outputs"

    with open(out_dir / "oversampling_plan.json", encoding="utf-8") as f:
        meta = json.load(f)
    class_names = meta["classes"]
    class_to_idx = meta["class_to_idx"]

    records = load_records(data_dir, out_dir / "splits.csv", class_to_idx)
    train_labels = [label for _, label in records["train"]]

    # Verify that dataset records match oversampling plan metadata
    actual = Counter(train_labels)
    for cls, info in meta["plan"].items():
        if actual[class_to_idx[cls]] != info["train_count"]:
            raise ValueError(
                f"splits.csv and oversampling_plan.json disagree for '{cls}'. "
                "Re-run step1_split_data.py with --force."
            )
    targets = {class_to_idx[c]: p["epoch_target"] for c, p in meta["plan"].items()}
    sampler = EpochOversampler(train_labels, targets, seed)

    train_ds = WasteDataset(records["train"], train_transform(size))
    val_ds = WasteDataset(records["val"], eval_transform(size))
    test_ds = WasteDataset(records["test"], eval_transform(size))

    common = dict(
        batch_size=batch_size,
        num_workers=num_workers,
        pin_memory=torch.cuda.is_available(),
        persistent_workers=num_workers > 0,
    )
    train_loader = DataLoader(
        train_ds, sampler=sampler, drop_last=True,
        generator=torch.Generator().manual_seed(seed), **common)
    val_loader = DataLoader(val_ds, shuffle=False, **common)
    test_loader = DataLoader(test_ds, shuffle=False, **common)

    return {
        "train": train_loader,
        "val": val_loader,
        "test": test_loader,
        "class_names": class_names,
        "class_to_idx": class_to_idx,
        "sampler": sampler,
        "plan": meta["plan"],
    }


def save_preview(loader, class_names, path, n=16):
    """De-normalizes and saves a 4x4 visual inspection grid of augmented training images."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    Path(path).parent.mkdir(parents=True, exist_ok=True)
    images, labels = next(iter(loader))
    mean = torch.tensor(IMAGENET_MEAN).view(3, 1, 1)
    std = torch.tensor(IMAGENET_STD).view(3, 1, 1)
    n = min(n, len(images))
    fig, axes = plt.subplots(4, 4, figsize=(10, 10))
    for ax in axes.flat:
        ax.axis("off")
    for ax, img, lab in zip(axes.flat, images[:n], labels[:n]):
        ax.imshow((img * std + mean).clamp(0, 1).permute(1, 2, 0).numpy())
        ax.set_title(class_names[int(lab)], fontsize=9)
    fig.tight_layout()
    fig.savefig(path, dpi=100)
    plt.close(fig)


def main():
    """Runs DataLoader verification, verifies batch shapes, and benchmark load throughput."""
    parser = argparse.ArgumentParser(description="Data loader self-test")
    parser.add_argument("--batch-size", type=int, default=16)
    parser.add_argument("--num-workers", type=int, default=4)
    parser.add_argument("--size", type=int, default=384)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--timing-batches", type=int, default=20,
                        help="number of batches to time for the speed check")
    args = parser.parse_args()

    data = build_dataloaders(args.batch_size, args.num_workers, args.size,
                             seed=args.seed)
    names = data["class_names"]
    sampler = data["sampler"]

    print(f"\nClasses ({len(names)}): {names}")
    print(f"Train images: {len(data['train'].dataset)}   "
          f"per epoch: {len(sampler)}   batches: {len(data['train'])}")
    print(f"Val images:   {len(data['val'].dataset)}   batches: {len(data['val'])}")
    print(f"Test images:  {len(data['test'].dataset)}   batches: {len(data['test'])}")

    # Test multi-epoch sampling balance without triggering image I/O
    train_labels = [lbl for _, lbl in data["train"].dataset.records]
    for epoch in (0, 1):
        idx = sampler.epoch_indices(epoch)
        counts = Counter(train_labels[i] for i in idx)
        print(f"\nEpoch {epoch} class counts (target from plan):")
        for i, name in enumerate(names):
            target = data["plan"][name]["epoch_target"]
            flag = "" if counts[i] == target else "  <-- MISMATCH"
            print(f"  {name:<10}{counts[i]:>6}  (plan {target}){flag}")

    # Inspect first batch tensor dimensions and value ranges
    images, labels = next(iter(data["train"]))
    print(f"\nBatch images: {tuple(images.shape)} {images.dtype}, "
          f"range {images.min():.2f} to {images.max():.2f}")
    print(f"Batch labels: {tuple(labels.shape)} {labels.dtype}")

    out_path = ROOT / "outputs" / "augmentation_preview.png"
    save_preview(data["train"], names, out_path)
    print(f"Saved augmentation preview: {out_path}")

    # Measure disk I/O and preprocessing throughput
    n = min(args.timing_batches, len(data["train"]))
    start = time.time()
    for i, _ in enumerate(data["train"]):
        if i + 1 >= n:
            break
    elapsed = time.time() - start
    print(f"\nLoaded {n} batches in {elapsed:.1f}s "
          f"({elapsed / n:.2f}s per batch, "
          f"~{elapsed / n * len(data['train']) / 60:.1f} min per epoch of pure loading)")


if __name__ == "__main__":
    main()
